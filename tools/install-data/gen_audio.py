#!/usr/bin/env python3
"""Build-time header for the converter's sound banks (our own data only).

    gen_audio.py OUTPUT.h

- The plan: every kept sound of docs/sound-inventory.md with its scene banks
  (tools/pack-amiga-sfx.py's rules), Paula period and cut
  (tools/sfx-bank-policy.json), as integers in output samples.
- The resampler: a polyphase windowed-sinc FIR from 44,100 Hz to the Paula
  rate of period 424 (3,546,895 / 424 Hz): cutoff 0.95 of the output
  Nyquist, 8 zero crossings each side, Blackman window, 256 phases, Q15
  taps; each phase sums to exactly 32768.
- A quarter sine in Q15 (1025 entries) for the fades and crossfades.
"""
import importlib.util
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PAULA_CLOCK = 3546895
SOURCE_RATE = 44100
PHASES = 256
ZEROS = 8
FIELD_CLOCKS = PAULA_CLOCK / 50
BANKS = {'run': 1, 'front': 2, 'results': 4, 'clear': 8}
RUN_SCENES = {'gameplay', 'shop', 'pause'}


def load_bank_tool():
    spec = importlib.util.spec_from_file_location('sfx_bank', ROOT / 'tools/sfx-bank.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def banks_of(s):
    scenes = set(s['scenes'])
    if scenes & RUN_SCENES:
        return BANKS['run'] | (BANKS['front'] if 'front' in scenes else 0)
    if scenes == {'front'}:
        return BANKS['front']
    if scenes == {'results'}:
        return BANKS['results']
    if scenes == {'clear'}:
        return BANKS['clear']
    raise SystemExit(f"{s['id']} {s['name']}: no scene bank for {sorted(scenes)}")


def plan(sb):
    import json
    policy = json.loads((ROOT / 'tools/sfx-bank-policy.json').read_text())
    sounds = sb.kept_sounds()
    sb.classify(sounds, policy)
    rows = []
    for s in sorted(sounds, key=lambda s: s['id']):
        rate_choice, choice = sb.current(s, policy)
        period = sb.period(rate_choice)
        rate = PAULA_CLOCK / period
        pitch = sb.max_pitch(s, policy)
        if s['class'] == 'long':
            spec = policy['long'][str(s['id'])]['cuts'][choice]
            if spec.get('drop'):
                kind, a, b, c = 'SFX_DROP', 0, 0, 0
            elif 'swellSeconds' in spec:
                kind, a, b, c = 'SFX_SWELL', int(round(spec['swellSeconds'] * rate)), max(1, int(rate) // 20), 0
            elif 'seconds' in spec:
                n = int(round(spec['seconds'] * rate))
                f = int(round(spec.get('fadeSeconds', min(0.5, 0.25 * spec['seconds'])) * rate))
                kind, a, b, c = 'SFX_HEAD', n, f, 0
            else:
                kind = 'SFX_LOOP'
                a = int(round(spec['loopStart'] * rate))
                b = int(round(spec['loopSeconds'] * rate))
                c = int(round(spec.get('crossfadeSeconds', min(0.25, spec['loopSeconds'] / 4)) * rate))
        else:
            # Crop after the last window (2 ms) whose peak reaches the threshold.
            kind, a, b, c = 'SFX_CROP', round(10 ** (choice / 20) * 32768), max(1, int(rate) // 500), 0
        # A one-shot must play for more than 1.2 PAL fields at its top pitch.
        least = 0
        if kind != 'SFX_LOOP':
            least = 2
            while least * max(124, period / pitch) / FIELD_CLOCKS <= 1.2:
                least += 2
        rows.append((s['id'], banks_of(s), period, kind, a, b, c, least, s['name']))
    return rows


def resampler(period):
    out_rate = PAULA_CLOCK / period
    fc2 = 0.95 * out_rate / SOURCE_RATE         # cutoff as a fraction of the input rate, x2
    half = ZEROS / fc2                           # window half-width in input samples
    taps = 2 * math.ceil(half)
    centre = taps // 2 - 1
    table = []
    for p in range(PHASES):
        row = []
        for j in range(taps):
            t = j - centre - p / PHASES
            x = fc2 * t
            sinc = 1.0 if t == 0 else math.sin(math.pi * x) / (math.pi * x)
            u = t / half
            w = 0.42 + 0.5 * math.cos(math.pi * u) + 0.08 * math.cos(2 * math.pi * u) if abs(u) < 1 else 0.0
            row.append(fc2 * sinc * w)
        total = sum(row)
        q = [round(v / total * 32768) for v in row]
        q[max(range(taps), key=lambda j: abs(row[j]))] += 32768 - sum(q)
        table.append(q)
    return taps, centre, table


def main():
    sb = load_bank_tool()
    rows = plan(sb)
    periods = {r[2] for r in rows}
    if periods != {424}:
        raise SystemExit(f'the converter resamples to period 424 only, the plan has {sorted(periods)}')
    taps, centre, table = resampler(424)
    step = SOURCE_RATE * 424
    lines = ['/* Generated by tools/install-data/gen_audio.py; do not edit. */',
             '#ifndef DW_AUDIO_PLAN_H', '#define DW_AUDIO_PLAN_H',
             'enum { SFX_CROP, SFX_HEAD, SFX_SWELL, SFX_LOOP, SFX_DROP };',
             'enum { SFX_RUN = 1, SFX_FRONT = 2, SFX_RESULTS = 4, SFX_CLEAR = 8 };',
             '/* id, banks, period, kind, a, b, c, least bytes:',
             '   CROP a threshold (Q15), b window; HEAD a samples, b fade;',
             '   SWELL a samples, b envelope hop; LOOP a start, b samples, c crossfade. */',
             'typedef struct { unsigned short id, banks, period, kind; unsigned long a, b, c, least; } SfxPlan;',
             f'#define SFX_PLAN_COUNT {len(rows)}',
             'static const SfxPlan SFX_PLAN[SFX_PLAN_COUNT] = {']
    lines += [f'    {{{i}, {bk}, {p}, {k}, {a}, {b}, {c}, {least}}}, /* {name} */'
              for i, bk, p, k, a, b, c, least, name in rows]
    lines += ['};',
              f'#define SFX_SOURCE_RATE {SOURCE_RATE}u',
              f'#define SFX_STEP_WHOLE {step // PAULA_CLOCK}u',
              f'#define SFX_STEP_PART {step % PAULA_CLOCK}u',
              f'#define SFX_STEP_DENOM {PAULA_CLOCK}u',
              f'#define SFX_PHASES {PHASES}u',
              f'#define SFX_TAPS {taps}u',
              f'#define SFX_CENTRE {centre}u',
              'static const short SFX_FIR[SFX_PHASES][SFX_TAPS] = {']
    for row in table:
        lines.append('    {' + ','.join(str(v) for v in row) + '},')
    lines += ['};', '/* sin(k / 1024 * pi / 2) in Q15, k = 0..1024. */',
              'static const unsigned short SFX_SINE[1025] = {']
    sine = [round(math.sin(k / 1024 * math.pi / 2) * 32768) for k in range(1025)]
    for i in range(0, 1025, 16):
        lines.append('    ' + ','.join(str(v) for v in sine[i:i + 16]) + ',')
    lines += ['};', '#endif']
    Path(sys.argv[1]).write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
