#!/usr/bin/env python3
"""Compile immutable main-room index writes; never publish Create effects early."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = "c07daf5fbe940ae0a19503b5ba5137a56ee492753b1cea34b276a5cf7545fdb8"


def compile_room(manifest):
    if manifest["source"]["sha256"] != SOURCE or manifest["schemaVersion"] != 3:
        raise ValueError("unrecognized source manifest")
    room = next(r for r in manifest["resources"]["rooms"] if r["id"] == 11)
    instances = {r["instanceId"]: r for r in room["instances"]}
    occupied, commands, slot = {}, [], 0
    for expected_index, ordered in enumerate(room["instanceCreationOrder"]):
        r = instances[ordered["instanceId"]]
        if ordered["index"] != expected_index or ordered["objectId"] != r["objectId"]:
            raise ValueError("source creation order/identity mismatch")
        obj, x, y = r["objectId"], r["x"], r["y"]
        current = slot
        slot += 1
        if obj not in (60, 93, 99):
            continue
        cell = bit = before = after = 0
        if obj in (60, 93):
            if x % 16 or y % 16 or not (-512 <= x < 1536 and 0 <= y < 8192):
                raise ValueError("unsupported room terrain geometry")
            row, column = y // 16, (x + 512) // 16
            cell, bit = row * 128 + column, 0x8000 >> (row % 16)
            before = occupied.get(cell, 0)
            if obj == 60 and before & 192 == 192:
                raise ValueError("overflow-contact room requires scalar publication")
            after = (before + 64) | 27 if obj == 60 else before | 34
            occupied[cell] = after
        commands.append((r["instanceId"], current, obj, x, y, cell, bit, before, after))
    return slot, commands


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = ROOT / "extracted/utmt-0.9.2.0/manifest.json"
    manifest = json.loads(source.read_text())
    count, commands = compile_room(manifest)
    payload = ("// Generated by tools/generate-room-terrain-plan.py; do not edit.\n"
               f"static constexpr unsigned sourceCount={count};\n"
               "static constexpr Command commands[]={\n" +
               "".join("    {" + ",".join(map(str, command)) + "},\n" for command in commands) +
               "};\n").encode()
    sha = lambda data: hashlib.sha256(data).hexdigest()
    provenance = {
        "schemaVersion": 1, "sourceSha256": SOURCE, "extractor": manifest["extractor"],
        "manifestSha256": sha(source.read_bytes()),
        "generatorSha256": sha(Path(__file__).read_bytes()),
        "roomId": 11, "sourcePlacements": count, "commands": len(commands),
        "outputSha256": sha(payload),
    }
    files = {
        ROOT / "generated/amiga-room-terrain-plan.inc": payload,
        ROOT / "generated/amiga-room-terrain-plan.json":
            (json.dumps(provenance, indent=2, sort_keys=True) + "\n").encode(),
    }
    for path, contents in files.items():
        if args.check:
            if not path.exists() or path.read_bytes() != contents:
                raise SystemExit(f"stale room terrain plan: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents)
    print(f"Room terrain plan: {len(commands)} ordered commands, room 11")


if __name__ == "__main__":
    main()
