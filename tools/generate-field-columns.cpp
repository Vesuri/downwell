// Offline large-circle word commands. Portable raster is the oracle, not the
// original Windows GPU. Columns can be culled without visiting their rows.
#include "core/GoalFieldOutline.h"
#include <array>
#include <fstream>
#include <iostream>
#include <map>
#include <vector>

int main(int argc,char** argv){
    if(argc!=4)return 20;
    using Word=std::array<int,3>; // y, low, high
    using Column=std::vector<Word>;
    using Frame=std::array<unsigned,18>; // canonical x=14, columns -8..9
    std::map<Column,unsigned> columnIds;
    std::vector<Column> columns;
    std::map<Frame,unsigned> frameIds;
    std::vector<Frame> frames;
    std::vector<unsigned> radii;
    for(unsigned phase=0;phase<512;++phase){
        std::map<std::pair<int,int>,std::array<unsigned,2>> raster;
        downwell::GoalFieldOutline shape;
        shape.setRasterCircle(14,0,128*256+phase);
        bool valid=true;
        shape.draw([&](int x,int y,unsigned pen){
            const int col=x>=0?x/16:-((15-x)/16);
            if(col < -8||col>9||y < -131||y>131){valid=false;return;}
            const unsigned mask=0x8000u>>(x-col*16);
            auto& value=raster[{col,y}];
            for(unsigned p=0;p<2;++p)value[p]=(value[p]&~mask)|((pen&(1u<<p))?mask:0);
        });
        if(!valid)return 20;
        Frame frame{};
        for(int col=-8;col<=9;++col){
            Column data;
            for(const auto& [position,pens]:raster)if(position.first==col&&(pens[0]|pens[1]))
                data.push_back({position.second,int(pens[0]),int(pens[1])});
            auto inserted=columnIds.emplace(data,unsigned(columns.size()));
            if(inserted.second)columns.push_back(data);
            frame[col+8]=inserted.first->second;
        }
        auto inserted=frameIds.emplace(frame,unsigned(frames.size()));
        if(inserted.second)frames.push_back(frame);
        radii.push_back(inserted.first->second);
    }
    unsigned count=0;for(const auto& col:columns)count+=col.size();
    if(count>65535||columns.size()>65535)return 20;
    // Resident top/bottom arcs. Within eight pixels of the viewport centre,
    // the middle of the circle is entirely outside the viewport. Store white
    // coverage plus total coverage: red is mask & ~white, supplied by the
    // blitter's minterm instead of a third resident plane.
    using Band=std::vector<unsigned short>;
    std::map<Band,unsigned> bandIds;
    std::vector<Band> bands;
    struct Placement { int top;unsigned id; };
    std::vector<std::array<Placement,2>> bandFrames;
    for(unsigned f=0;f<frames.size();++f){
        unsigned phase=0;while(radii[phase]!=f)++phase;
        std::array<std::array<unsigned short,22>,264> raster{};
        downwell::GoalFieldOutline shape;
        shape.setRasterCircle(88,132,128*256+phase);
        shape.draw([&](int x,int y,unsigned pen){
            if(x<0||x>=176)return;
            const unsigned bit=0x8000u>>(x&15);
            if(pen==1)raster[y][x/16]|=bit;else raster[y][x/16]&=~bit;
            raster[y][11+x/16]|=bit;
        });
        std::array<Placement,2> frame{};unsigned n=0;
        for(unsigned y=0;y<264;){
            auto used=[&](unsigned row){for(unsigned x=11;x<22;++x)if(raster[row][x])return true;return false;};
            if(!used(y)){++y;continue;}
            const unsigned first=y;while(y<264&&used(y))++y;
            Band image{static_cast<unsigned short>(y-first)};
            for(unsigned p=0;p<2;++p)for(unsigned row=first;row<y;++row)
                for(unsigned x=0;x<11;++x)image.push_back(raster[row][p*11+x]);
            auto inserted=bandIds.emplace(image,unsigned(bands.size()));
            if(inserted.second)bands.push_back(image);
            if(n==2)return 20;
            frame[n++]={int(first)-132,inserted.first->second};
        }
        if(n!=2)return 20;
        bandFrames.push_back(frame);
    }
    std::ofstream out(argv[1]);
    out<<"// Generated by generate-field-columns/v4; do not edit.\n"
           "#ifndef DOWNWELL_FIELD_COLUMNS_GENERATED_H\n#define DOWNWELL_FIELD_COLUMNS_GENERATED_H\n"
           "namespace downwell {\n"
           "struct FieldColumnWord { short row,wordOffset; unsigned short low,high; };\n"
           "static const unsigned short fieldColumnRadii[512]={\n";
    for(auto id:radii)out<<id<<',';
    out<<"\n};\nstatic const unsigned short fieldColumnFrames[][18]={\n";
    for(const auto& frame:frames){out<<'{';for(auto id:frame)out<<id<<',';out<<"},\n";}
    out<<"};\nstatic const unsigned short fieldColumnOffsets[]={\n0,";
    unsigned offset=0;for(const auto& col:columns){offset+=col.size();out<<offset<<',';}
    std::ofstream commands(argv[3],std::ios::binary);unsigned commandChecksum=0;
    for(const auto& col:columns)for(const auto& word:col){
        const int values[]={word[0],word[0]*24,word[1],word[2]};
        for(int value:values){const unsigned w=unsigned(value)&65535u;
            commands.put(char(w>>8));commands.put(char(w));
            commandChecksum=((commandChecksum<<5)|(commandChecksum>>27))^w;
        }
    }
    commands.close();if(!commands)return 20;
    out<<"\n};\nstatic constexpr unsigned fieldColumnBytes="<<count*8<<";\n"
       <<"static constexpr unsigned fieldColumnChecksum="<<commandChecksum<<"u;\n"
       <<"#ifndef DOWNWELL_PLATFORM_AMIGA\nstatic const FieldColumnWord fieldColumnWords[]={\n";
    for(const auto& col:columns)for(const auto& word:col)
        out<<'{'<<word[0]<<','<<word[0]*24<<','<<word[1]<<','<<word[2]<<"},\n";
    out<<"};\n#endif\nstruct FieldBandPlacement { short top;unsigned short image; };\n"
           "struct FieldBandImage { unsigned short wordOffset,height; };\n"
           "static const FieldBandPlacement fieldBandFrames[][2]={\n";
    for(const auto& frame:bandFrames){out<<'{';for(const auto& p:frame)out<<'{'<<p.top<<','<<p.id<<"},";out<<"},\n";}
    out<<"};\nstatic const FieldBandImage fieldBandImages[]={\n";
    unsigned bandWords=0;
    for(const auto& band:bands){out<<'{'<<bandWords<<','<<band[0]<<"},\n";bandWords+=band.size()-1;}
    if(bandWords>65535)return 20;
    std::ofstream binary(argv[2],std::ios::binary);unsigned checksum=0;
    for(const auto& band:bands)for(unsigned i=1;i<band.size();++i){
        const unsigned word=band[i];binary.put(char(word>>8));binary.put(char(word));
        checksum=((checksum<<5)|(checksum>>27))^word;
    }
    binary.close();if(!binary)return 20;
    out<<"};\nstatic constexpr unsigned fieldBandBytes="<<bandWords*2<<";\n"
       <<"static constexpr unsigned fieldBandChecksum="<<checksum<<"u;\n"
       <<"#ifndef DOWNWELL_PLATFORM_AMIGA\nstatic const unsigned short fieldBandPixels[]={\n";
    for(const auto& band:bands){for(unsigned i=1;i<band.size();++i)out<<band[i]<<',';out<<'\n';}
    out<<"};\n#endif\n}\n#endif\n";out.close();
    if(!out)return 20;
    std::cout<<frames.size()<<" frames, "<<columns.size()<<" unique columns, "<<count
             <<" words; "<<count*8+frames.size()*36+(columns.size()+1)*2+1024<<" payload bytes; "
             <<bands.size()<<" resident arc images, "<<bandWords*2<<" Chip bytes\n";
    return 0;
}
