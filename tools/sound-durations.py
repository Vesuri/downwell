#!/usr/bin/env python3
"""Write generated/sound-durations.inc: every sound's source length in
60 Hz steps, for the core's audio_is_playing model (W2.3,
src/core/SourceSoundDurations.h), and generated/sound-gains.inc: each
asset's volume (stored as a float) as the double GameMaker reads back.

A sound started during step S reads as playing at step S + k while
k < ticks, where ticks = ceil(frames * 60 / rate) of the decoded source.
GameMaker's audio thread makes the exact boundary jitter by a few
milliseconds in the original; this is the deterministic port's contract.
Only lengths and volumes are written, no audio. --check fails if a table is stale.
"""
import argparse
import hashlib
import json
import math
import struct
import subprocess
from pathlib import Path

VERSION = "1.1.0"
ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "extracted/audio/manifest.json"
OUTPUT = ROOT / "generated/sound-durations.inc"
GAINS = ROOT / "generated/sound-gains.inc"


def frames(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "a:0", "-count_packets",
                          "-show_entries", "stream=sample_rate,duration_ts", "-of", "json", str(path)],
                         check=True, capture_output=True, text=True).stdout
    stream = json.loads(out)["streams"][0]
    return int(stream["duration_ts"]), int(stream["sample_rate"])


def render():
    data = MANIFEST.read_bytes()
    sounds = sorted(json.loads(data)["sounds"], key=lambda s: s["id"])
    if [s["id"] for s in sounds] != list(range(len(sounds))):
        raise SystemExit("sound ids are not dense")
    ticks = []
    for s in sounds:
        count, rate = frames(MANIFEST.parent / s["output"])
        ticks.append(min(65535, math.ceil(count * 60 / rate)))
    rows = []
    for i in range(0, len(ticks), 12):
        rows.append(",".join(str(t) for t in ticks[i:i + 12]) + ",")
    return (f"// Generated by tools/sound-durations.py {VERSION} from\n"
            f"// extracted/audio/manifest.json sha256 {hashlib.sha256(data).hexdigest()[:16]}.\n"
            f"// Source length of each of the {len(ticks)} sound resources in 60 Hz steps (ceil).\n"
            + "\n".join(rows) + "\n")


def render_gains():
    data = MANIFEST.read_bytes()
    sounds = sorted(json.loads(data)["sounds"], key=lambda s: s["id"])
    rows = []
    for s in sounds:
        bits = struct.unpack(">Q", struct.pack(">d", struct.unpack("<f", struct.pack("<f", s["volume"]))[0]))[0]
        rows.append(f"{{0x{bits >> 32:08x}u,0x{bits & 0xffffffff:08x}u}},")
    lines = [" ".join(rows[i:i + 4]) for i in range(0, len(rows), 4)]
    return (f"// Generated by tools/sound-durations.py {VERSION} from\n"
            f"// extracted/audio/manifest.json sha256 {hashlib.sha256(data).hexdigest()[:16]}.\n"
            f"// Volume of each of the {len(rows)} sound resources: the float as a double {{high, low}}.\n"
            + "\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = ((OUTPUT, render()), (GAINS, render_gains()))
    if args.check:
        for path, text in outputs:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"{path.relative_to(ROOT)} is stale: run tools/sound-durations.py")
            print(f"{path.relative_to(ROOT)} verified")
        return
    OUTPUT.parent.mkdir(exist_ok=True)
    for path, text in outputs:
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
