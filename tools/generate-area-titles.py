#!/usr/bin/env python3
"""Extract object-372 area labels; copyrighted payload stays in generated/."""
import argparse
import configparser
import hashlib
import json
from pathlib import Path

VERSION = 1

def extract(raw):
    ini = configparser.ConfigParser(interpolation=None)
    ini.read_string(raw.decode("utf-8-sig"))
    return [(language, area, ini[language].get(f"area{area}", " "))
            for language in ini.sections() for area in range(6)]

def generate(source, output):
    raw = source.read_bytes()
    titles = extract(raw)
    lines = ["// Generated by generate-area-titles.py; do not commit.",
             '#include "core/LevelNumberText.h"', "namespace downwell::area_titles {"]
    for i, (_, _, text) in enumerate(titles):
        tokens = ",".join(str(ord(c)) for c in text) or "0"
        lines.append(f"static const unsigned text{i}[] = {{{tokens}}};")
    lines.append("static const AreaTitle entries[] = {")
    for i, (language, area, text) in enumerate(titles):
        lines.append(f"{{{json.dumps(language)}, {area}, text{i}, {len(text)}}},")
    lines += ["};", "static constexpr unsigned count=sizeof(entries)/sizeof(entries[0]);", "}"]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines)+"\n", encoding="utf-8")
    manifest = {"schemaVersion": 1, "tool": {"name": Path(__file__).name, "version": VERSION,
                "sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest()},
                "input": {"name": source.name, "sha256": hashlib.sha256(raw).hexdigest()},
                "objectId": 372, "areaIds": list(range(6)), "languages": sorted({v[0] for v in titles}),
                "entryCount": len(titles), "outputSha256": hashlib.sha256(output.read_bytes()).hexdigest()}
    output.with_suffix(".json").write_text(json.dumps(manifest, indent=2)+"\n", encoding="utf-8")
    print(f"Prepared {len(titles)} localized area labels")

if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=root/"data/language.ini")
    parser.add_argument("--output", type=Path, default=root/"generated/downwell-area-titles.h")
    args = parser.parse_args()
    generate(args.source, args.output)
