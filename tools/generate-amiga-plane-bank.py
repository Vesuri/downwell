#!/usr/bin/env python3
"""Intern immutable DMA planes offline; retain DWAP as the CPU/reference view."""
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RECORD = struct.Struct('>HHhhHHHHII')


def build(pack):
    magic, version, header, count = struct.unpack_from('>4sHHI', pack)
    assert (magic, version, header) == (b'DWAP', 2, 20)
    sources = set()
    for i in range(count):
        r = RECORD.unpack_from(pack, 20 + i * RECORD.size)
        if r[7] != 3:  # Hardware sprite streams never pass through the BOB blitter.
            continue
        offset, length = r[8:]
        plane = (r[6] // 8) * r[5]
        assert plane and r[6] % 16 == 0 and length == plane * 3
        assert offset % 2 == 0 and offset + length <= len(pack)
        sources.add((offset, plane))
    streams = {pack[o + p*n:o + (p+1)*n] for o, n in sources for p in range(3)}
    payload, offsets = bytearray(), {}
    for stream in sorted(streams, key=lambda s: (-len(s), s)):
        at = payload.find(stream)
        while at >= 0 and at % 2:
            at = payload.find(stream, at + 1)
        if at < 0:
            overlap = 0
            for size in range(min(len(payload), len(stream)) // 2 * 2, 0, -2):
                if payload[-size:] == stream[:size]:
                    overlap = size
                    break
            at = len(payload) - overlap
            payload.extend(stream[overlap:])
        offsets[stream] = at
    start = 48 + len(sources) * 20
    bank = bytearray(struct.pack('>4sHHII32s', b'DWPL', 1, 48, len(sources), len(pack),
                                 hashlib.sha256(pack).digest()))
    for o, n in sorted(sources):
        bank.extend(struct.pack('>IIIII', o, n, *(start + offsets[pack[o+p*n:o+(p+1)*n]] for p in range(3))))
    bank.extend(payload)
    bank.extend(b'\0\0')  # Shifted source/mask extra-fetch guard, as in DWAP.
    # Exhaustive byte oracle, including transparent masks and aliased substreams.
    for i, (o, n) in enumerate(sorted(sources)):
        _, _, *planes = struct.unpack_from('>IIIII', bank, 48+i*20)
        for p, at in enumerate(planes):
            assert at % 2 == 0 and bank[at:at+n] == pack[o+p*n:o+(p+1)*n]
    return bytes(bank), len(sources), len(payload)


def main():
    source = ROOT / 'generated/amiga-game.dwap'
    bank, records, payload = build(source.read_bytes())
    (ROOT / 'generated/amiga-game.planes').write_bytes(bank)
    digest = hashlib.sha256(source.read_bytes()).digest()
    (ROOT / 'generated/amiga-game-planes.h').write_text(
        '// Generated by generate-amiga-plane-bank/v1; do not edit.\n'
        f'#define DOWNWELL_GAME_PLANE_BYTES {len(bank)}u\n'
        'static const unsigned char downwellGamePlaneSourceHash[32]={' +
        ','.join(map(str, digest)) + '};\n')
    inputs = ['data/data.win', 'generated/amiga-game.dwap', 'tools/generate-amiga-plane-bank.py']
    manifest = {'tool': 'generate-amiga-plane-bank/v1', 'records': records,
                'payload_bytes': payload, 'bank_bytes': len(bank),
                'inputs': {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in inputs},
                'sha256': hashlib.sha256(bank).hexdigest()}
    (ROOT / 'generated/amiga-game-planes.json').write_text(json.dumps(manifest, indent=2)+'\n')
    print(f'Plane bank: {records} source views, {payload} payload bytes, {len(bank)} Chip bytes')


if __name__ == '__main__':
    main()
