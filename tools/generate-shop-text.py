#!/usr/bin/env python3
"""Prepare immutable Shop language strings; copyrighted output stays generated."""
import argparse
import configparser
import hashlib
import json
from pathlib import Path

VERSION = 2
KEYS = tuple(f"ug{kind}{i}" for i in range(100, 106) for kind in ("Name", "Desc")) + (
    "shopExit", "shopPurchased", "menuBack", "shopSold", "shopGreet0", "shopGreet1", "shopGreet2",
    "shopBye0", "shopBye1", "shopBye2", "shopPoor", "shopWhat0", "shopWhat1")

# W1.8 merchant speech (scrRisingTextShop): only these keys, so the Amiga
# executable does not carry the menu labels and descriptions as text.
SPEECH_KEYS = ("shopSold", "shopGreet0", "shopGreet1", "shopGreet2", "shopBye0", "shopBye1",
               "shopBye2", "shopPoor", "shopWhat0", "shopWhat1")

def extract(raw):
    ini = configparser.ConfigParser(interpolation=None)
    ini.read_string(raw.decode("utf-8-sig"))
    return [(language, key, ini[language].get(key, " ").replace("*", "#"))
            for language in ini.sections() for key in KEYS]

def literal(text):
    # Fixed three-digit octal escapes preserve UTF-8 bytes on every target
    # compiler, including adjacent digits and quotes/backslashes in translations.
    return '"' + ''.join(f"\\{b:03o}" for b in text.encode("utf-8")) + '"'

def write(source, raw, rows, keys, namespace, output):
    lines = ['// Generated by generate-shop-text.py; do not commit.',
             '#include "core/ShopText.h"', f'namespace downwell::{namespace} {{',
             'static const ShopLanguageEntry entries[] = {']
    lines += ['{' + ','.join(literal(value) for value in row) + '},' for row in rows]
    lines += ['};', 'static constexpr unsigned count=sizeof(entries)/sizeof(entries[0]);', '}']
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines)+'\n', encoding='utf-8')
    manifest = {'schemaVersion': 1, 'tool': {'name': Path(__file__).name, 'version': VERSION,
                'sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest()},
                'input': {'name': source.name, 'sha256': hashlib.sha256(raw).hexdigest()},
                'objectId': 277, 'keys': keys, 'entryCount': len(rows),
                'outputSha256': hashlib.sha256(output.read_bytes()).hexdigest()}
    output.with_suffix('.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8')

def generate(source, output, speech_output):
    raw = source.read_bytes()
    rows = extract(raw)
    write(source, raw, rows, KEYS, 'shop_language', output)
    speech = [row for row in rows if row[1] in SPEECH_KEYS]
    write(source, raw, speech, SPEECH_KEYS, 'shop_speech', speech_output)
    print(f'Prepared {len(rows)} localized Shop strings, {len(speech)} speech strings')

if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=root/'data/language.ini')
    parser.add_argument('--output', type=Path, default=root/'generated/downwell-shop-text.h')
    parser.add_argument('--speech-output', type=Path, default=root/'generated/downwell-shop-speech.h')
    args = parser.parse_args()
    generate(args.source, args.output, args.speech_output)
