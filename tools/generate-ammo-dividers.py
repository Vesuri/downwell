#!/usr/bin/env python3
"""Host-compose small-capacity HUD dividers; keep source binary64 draw order."""
import hashlib
import json
import math
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
digest = lambda data: hashlib.sha256(data).hexdigest()
pack = (ROOT / "generated/amiga-hud.dwap").read_bytes()
provenance = json.loads((ROOT / "generated/amiga-hud.packing.json").read_text())
assert digest(pack) == provenance["packSha256"]
magic, version, directory, count = struct.unpack_from(">4sHHI", pack)
assert (magic, version) == (b"DWAP", 2)
stamps = {}
for i in range(count):
    sprite, frame, ox, oy, width, height, stride, flags, offset, size = struct.unpack_from(
        ">HHhhHHHHII", pack, directory + 24*i)
    if sprite != 421 or frame > 1:
        continue
    assert (ox, oy, width, height, stride) == (0, 0, 12, 8, 16)
    assert offset + 32 <= len(pack)
    stamps[frame] = [(struct.unpack_from(">H", pack, offset + 2*y)[0],
                      struct.unpack_from(">H", pack, offset + 16 + 2*y)[0]) for y in range(8)]
assert set(stamps) == {0, 1}
blocks = [tuple([(0, 0)] * 8)]
images = []
for capacity in range(17):
    for ammo in range(capacity + 1):
        column = [(0, 0)] * 284

        def draw(frame, y):
            y = math.floor(y)
            for row, (low, high) in enumerate(stamps[frame]):
                if not 0 <= y + row < 284:
                    continue
                mask = (low | high) & 0xfff0
                a, b = column[y + row]
                column[y + row] = ((a & ~mask) | (low & mask), (b & ~mask) | (high & mask))

        if capacity:
            spacing = (1.0 / capacity) * 184.0
            filled = (float(ammo) / capacity) * 184.0
            levels, level = [], 184.0
            while level > 0:
                levels.append(level)
                level -= spacing
            for level in levels:
                if level < filled:
                    draw(1, 229.0 - level)
            for level in levels:
                position = 229.0 - level
                if level < filled:
                    draw(0, position)
                    draw(1, position + 1.0)
                    draw(1, position - 1.0)
                elif level == filled or level == 1.0:
                    draw(1, position + 1.0)
        image = []
        column += [(0, 0)] * 4  # 36 complete blocks, including display padding.
        for first in range(0, 288, 8):
            block = tuple(column[first:first+8])
            if block not in blocks:
                blocks.append(block)
            image.append(blocks.index(block))
        images.append(image)
assert len(blocks) <= 256, "block dictionary no longer fits byte indices"
lines = ["// Generated by generate-ammo-dividers.py/v2; copyrighted derived data, do not commit.",
         "namespace downwell_ammo_dividers {",
         "static const unsigned short stamps[2][8][2] = {" ]
for frame in range(2):
    lines.append("{" + ",".join("{%d,%d}" % pair for pair in stamps[frame]) + "},")
lines += ["};", "static const unsigned short blocks[][16] = {"]
lines += ["{" + ",".join(str(word) for pair in block for word in pair) + "}," for block in blocks]
lines += ["};", "static const unsigned char images[][36] = {"]
lines += ["{" + ",".join(map(str, image)) + "}," for image in images]
lines += ["};", "}", ""]
output = "\n".join(lines).encode()
path = ROOT / "generated/amiga-ammo-dividers.h"
if not path.exists() or path.read_bytes() != output:
    path.write_bytes(output)
size = len(blocks)*32 + len(images)*36 + 64
manifest = dict(schemaVersion=1, generator="generate-ammo-dividers.py/v2",
    generatorSha256=digest(Path(__file__).read_bytes()), sourceSha256=provenance["sourceSha256"],
    extractor=provenance["extractor"], inputPackSha256=digest(pack), outputSha256=digest(output),
    spriteId=421, frames=[0, 1], capacities=[0, 16], images=len(images),
    blocks=len(blocks), blockRows=8, dataBytes=size)
path.with_suffix(".json").write_text(json.dumps(manifest, indent=2) + "\n")
print(f"Prepared {len(images)} divider compositions, {size} bytes")
