#!/usr/bin/env python3
"""WI.3: pack the derived tables into the installed file Downwell.tables.

The executable links no table derived from the player's files
(docs/amiga-input-inventory.md). They are installed as one file instead,
read whole at startup (AmigaTables) and bound by tag.

Layout, big-endian: "DWTB", u16 version, u16 count, then count entries of
{u32 tag, u32 offset, u32 bytes}, then the payloads, each at a 4-byte
aligned offset. generated/amiga-tables.h gives the file's size and the
tags (layout only, no table bytes). --check fails if either is stale.
"""
import argparse
import runpy
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'generated/amiga-tables.bin'
HEADER = ROOT / 'generated/amiga-tables.h'
VERSION = 1

# tag: (generated input, what the executable binds it to)
SECTIONS = [
    ('ROOM', 'downwell-runtime-rooms.dwrm', 'RoomPack'),
    ('OBJT', 'downwell-objects.dwob', 'ObjectPack'),
    ('SCOL', 'downwell-sprites.dwsc', 'SpriteCollisionPack'),
    ('STMP', 'amiga-effect-stamps.dwef', 'AmigaEffectStampBank'),
    ('TPH6', 'amiga-terrain-phase6.bin', 'AmigaTerrainPainter::bindPrepared'),
    ('TINI', 'amiga-initial-terrain.bin', 'the initial terrain'),
]
# The header tables (tools/install-table-headers.py): one section per header.
INSTALL = runpy.run_path(str(ROOT / 'tools/install-table-headers.py'))
SECTIONS += [(tag, f'installed/{name}.bin', f'generated/installed/{name}')
             for tag, name in INSTALL['HEADERS']]


def tag_value(tag):
    return struct.unpack('>I', tag.encode('ascii'))[0]


def build():
    payloads = [(tag, (ROOT / 'generated' / name).read_bytes()) for tag, name, _ in SECTIONS]
    start = 8 + 12 * len(payloads)
    directory, body = b'', bytearray()
    for tag, data in payloads:
        body += b'\0' * (-(start + len(body)) % 4)
        directory += struct.pack('>III', tag_value(tag), start + len(body), len(data))
        body += data
    blob = b'DWTB' + struct.pack('>HH', VERSION, len(payloads)) + directory + bytes(body)
    lines = [f'// Generated by tools/pack-amiga-tables.py v{VERSION}; do not edit.',
             '// Downwell.tables: its size and tags only.',
             '#pragma once',
             f'#define DOWNWELL_TABLES_BYTES {len(blob)}u',
             f'#define DOWNWELL_TABLES_VERSION {VERSION}u',
             f'#define DOWNWELL_TABLES_COUNT {len(payloads)}u']
    for tag, name, use in SECTIONS:
        lines.append(f'#define DOWNWELL_TABLE_{tag} 0x{tag_value(tag):08x}u // {name} ({use})')
    return blob, '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    blob, header = build()
    if args.check:
        stale = [p for p, want in ((OUTPUT, blob), (HEADER, header.encode()))
                 if not p.exists() or p.read_bytes() != want]
        for path in stale:
            print(f'{path.relative_to(ROOT)} is stale; run tools/pack-amiga-tables.py', file=sys.stderr)
        return 1 if stale else 0
    OUTPUT.write_bytes(blob)
    HEADER.write_text(header)
    print(f'wrote {OUTPUT.relative_to(ROOT)}: {len(blob)} bytes, {len(SECTIONS)} tables')
    return 0


if __name__ == '__main__':
    sys.exit(main())
