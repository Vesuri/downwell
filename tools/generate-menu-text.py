#!/usr/bin/env python3
"""Prepare the pause, option, palette, stats and confirm menu strings.

Only the English rows are kept: the Amiga font banks carry font 2's ASCII
glyphs, and the build has no language menu. '*' (langString's newline) is
written as '#', as string_hash_to_newline expects. Output stays generated.
"""
import argparse
import configparser
import hashlib
import json
from pathlib import Path

VERSION = 1
LANGUAGE = "english"
KEYS = ("menuPaused", "menuResume", "menuRetry", "menuStyleSelect", "menuPalette", "menuStats",
        "menuOption", "menuQuickStart", "menuQuit", "menuConfirmQuit", "menuConfirmReset",
        "menuYes", "menuNo", "menuBack", "menuBGM", "menuTimer", "menuVolume", "menuOn",
        "menuOff", "menuMaxed", "menuHardMode", "menuLocked", "statFurthest", "statGems",
        "statCombo", "statFastestTime",
        *(f"area{i}" for i in range(6)),
        *(f"styleName{i}" for i in range(5)), *(f"styleDesc{i}" for i in range(5)))


def literal(text):
    return '"' + ''.join(f"\\{b:03o}" for b in text.encode("utf-8")) + '"'


def generate(source, output):
    raw = source.read_bytes()
    ini = configparser.ConfigParser(interpolation=None)
    ini.read_string(raw.decode("utf-8-sig"))
    section = ini[LANGUAGE]
    rows = [(LANGUAGE, key, section.get(key, " ").replace("*", "#")) for key in KEYS]
    for _, key, value in rows:
        if any(ord(c) < 32 or ord(c) > 126 for c in value):
            raise SystemExit(f"{key}: English text outside font 2's ASCII range")
    lines = ["// Generated by generate-menu-text.py; do not commit.",
             '#include "core/ShopText.h"', "namespace downwell::menu_text {",
             "static const ShopLanguageEntry entries[] = {"]
    lines += ["{" + ",".join(literal(value) for value in row) + "}," for row in rows]
    lines += ["};", "static constexpr unsigned count=sizeof(entries)/sizeof(entries[0]);", "}"]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    manifest = {"schemaVersion": 1,
                "tool": {"name": Path(__file__).name, "version": VERSION,
                         "sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest()},
                "input": {"name": source.name, "sha256": hashlib.sha256(raw).hexdigest()},
                "language": LANGUAGE, "keys": KEYS, "entryCount": len(rows),
                "outputSha256": hashlib.sha256(output.read_bytes()).hexdigest()}
    output.with_suffix(".json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Prepared {len(rows)} menu strings")


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=root / "data/language.ini")
    parser.add_argument("--output", type=Path, default=root / "generated/downwell-menu-text.h")
    args = parser.parse_args()
    generate(args.source, args.output)
