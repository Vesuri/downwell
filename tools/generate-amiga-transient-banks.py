#!/usr/bin/env python3
"""Explicit transient-bank contracts. New banks require an owner and a budget."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION = 'generate-amiga-transient-banks/v1'
# Budgets are deliberately not inferred from payload sizes. Growth must be
# reviewed against scene peak residency, not silently enlarge an allocation.
# Upgrade owns the living player's DMA poses (16 KiB allowance), allowing the
# entire 221282-byte cavern CPU pack and 106574-byte DMA pack to retire.
BANKS = {'results': 24576, 'shop': 16384, 'clear': 188416}


def main():
    inputs = ['data/data.win', 'tools/generate-amiga-hud.py',
              'tools/generate-amiga-transient-banks.py']
    lines = [f'// Generated by {VERSION}; do not edit.', '#pragma once']
    banks = {}
    for name, budget in BANKS.items():
        path = f'generated/amiga-{name}.dwap'
        payload = (ROOT / path).read_bytes()
        if not payload or len(payload) > budget:
            raise SystemExit(f'{name}: {len(payload)} bytes exceeds explicit {budget} byte budget')
        inputs.append(path)
        lines += [f'#define DOWNWELL_{name.upper()}_BANK_BYTES {len(payload)}u',
                  f'#define DOWNWELL_{name.upper()}_BANK_BUDGET {budget}u']
        banks[name] = {'bytes': len(payload), 'budget': budget,
                       'owner': 'upgrade' if name == 'clear' else name,
                       'sha256': hashlib.sha256(payload).hexdigest()}
    manifest = {'tool': VERSION, 'banks': banks,
                'inputs': {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in inputs}}
    (ROOT / 'generated/amiga-transient-banks.h').write_text('\n'.join(lines) + '\n')
    (ROOT / 'generated/amiga-transient-banks.json').write_text(json.dumps(manifest, indent=2) + '\n')


if __name__ == '__main__':
    main()
