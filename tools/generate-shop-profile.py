#!/usr/bin/env python3
"""Export buttons from the source-checked natural route, never target state."""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
INPUTS = ["generated/downwell-rooms.dwrm", "generated/downwell-objects.dwob",
          "generated/downwell-builder-patterns.dwbp"]


def main():
    environment = dict(os.environ, DOWNWELL_VERIFY_NATURAL_EXIT="1",
                       DOWNWELL_EXPORT_SHOP_PROFILE="1")
    environment.pop("DOWNWELL_VERIFY_ROUTE_SWEEP", None)
    result = subprocess.run(["build/amiga-scene-runtime-test", *INPUTS], cwd=ROOT,
                            env=environment, text=True, capture_output=True)
    if result.returncode:
        sys.stderr.write(result.stdout + result.stderr)
        result.check_returncode()
    tapes = {}
    final = None
    for line in result.stdout.splitlines():
        if line.startswith("SHOP_TAPE "):
            values = list(map(int, line.split()[1:]))
            assert values[0] not in tapes
            tapes[values[0]] = values[1:]
        elif line.startswith("SHOP_FINAL "):
            assert final is None
            final = list(map(int, line.split()[1:]))
    assert set(tapes) == {1, 2} and final is not None and len(final) == 22
    assert all(tapes.values()) and all(0 <= v <= 7 for tape in tapes.values() for v in tape)
    lines = ["// Generated by tools/generate-shop-profile.py v1; buttons only.",
             "#ifndef DOWNWELL_GENERATED_SHOP_PROFILE_H",
             "#define DOWNWELL_GENERATED_SHOP_PROFILE_H", "namespace downwell {"]
    for level, tape in sorted(tapes.items()):
        lines.append(f"static constexpr unsigned char shopProfileLevel{level}[] = {{")
        lines.extend("    " + ",".join(map(str, tape[i:i+32])) + ","
                     for i in range(0, len(tape), 32))
        lines.append("};")
    lines.append("static constexpr long shopProfileFinal[] = {" +
                 ",".join(map(str, final[:4])) + "};")
    lines.append("static constexpr unsigned long shopProfileRandom[] = {" +
                 ",".join(str(v) + "UL" for v in final[4:]) + "};")
    lines += ["}", "#endif", ""]
    output = ROOT / "generated/shop-profile-input.h"
    output.write_text("\n".join(lines))
    sha = lambda path: hashlib.sha256(path.read_bytes()).hexdigest()
    manifest = {"tool": "generate-shop-profile.py", "version": 1, "seed": 4,
                "tool_sha256": sha(Path(__file__)),
                "inputs": {name: sha(ROOT / name) for name in INPUTS},
                "route_source_sha256": sha(ROOT / "tests/platform/amiga/AmigaSceneRuntimeTest.cpp"),
                "route_controller_sha256": sha(ROOT / "src/platform/amiga/AmigaNaturalRouteVerification.h"),
                "frames": {str(k): len(v) for k, v in tapes.items()},
                "header_sha256": sha(output), "final": final}
    (ROOT / "generated/shop-profile-input.manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n")
    print(f"Source-checked shop tape: {len(tapes[1])} + {len(tapes[2])} gameplay inputs")


if __name__ == "__main__":
    main()
