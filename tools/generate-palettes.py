#!/usr/bin/env python3
"""Prepare the PALETTE menu's colour sets from the pinned build.

scrShaderListInit (VM assembly) lists shaderAr[i] = [shader id, name]; the
objControlerN Draw GUI event applies that shader to the whole application
surface. Each listed fragment shader (GLSL ES source in data.win's SHDR
chunk) classifies a pixel as white, red, black or blue and replaces it with
colorL, colorM, colorD or colorS. The Amiga build draws with exactly
black, white and red, so a palette is the 12-bit form of those constants.
Output stays in generated/.
"""
import argparse
import hashlib
import json
import re
import struct
from pathlib import Path

VERSION = 1
ROOT = Path(__file__).resolve().parents[1]
NAMED = {"white": (1.0, 1.0, 1.0), "red": (1.0, 0.0, 0.0), "black": (0.0, 0.0, 0.0),
         "green": (0.0, 1.0, 0.0), "blue": (0.0, 126.0 / 256.0, 256.0 / 256.0)}


def require(condition, message):
    if not condition:
        raise SystemExit(message)


def shaders(data):
    u32 = lambda offset: struct.unpack_from("<I", data, offset)[0]
    require(data[:4] == b"FORM", "data.win is not a FORM container")
    pos = 8
    while pos < len(data) and data[pos:pos + 4] != b"SHDR":
        pos += 8 + u32(pos + 4)
    require(pos < len(data), "missing SHDR chunk")
    text = lambda offset: data[offset:offset + u32(offset - 4)].decode("utf-8")
    result = {}
    for index in range(u32(pos + 8)):
        entry = u32(pos + 12 + 4 * index)
        # name, type, GLSL ES vertex, GLSL ES fragment, ...
        result[index] = (text(u32(entry)), text(u32(entry + 12)))
    return result


def palette_list(assembly):
    lines = [line.strip() for line in assembly.splitlines()]
    ids, names = [], []
    for i, line in enumerate(lines):
        # shaderAr[i][0] = id: the value, its conversion, then the array target.
        if line.startswith("pushi.e ") and lines[i + 1:i + 3] == ["conv.i.v", "pushi.e -5"]:
            ids.append(int(line.split()[1]))
        match = re.match(r'push\.s "([^"]*)"@\d+$', line)
        if match:
            names.append(match.group(1))
    require(len(ids) == len(names) and ids, "unexpected scrShaderListInit shape")
    require("pop.v.v global.shaderArMax" in lines, "missing shaderArMax")
    return list(zip(ids, names))


def colour(expression):
    expression = re.sub(r"\s+", "", expression)
    if expression in NAMED:
        return NAMED[expression]
    match = re.fullmatch(r"vec3\(([^,]+),([^,]+),([^,]+)\)", expression)
    require(match, f"unsupported colour expression {expression}")
    values = []
    for part in match.groups():
        number = re.fullmatch(r"([0-9.]+)(?:/256\.0)?", part)
        require(number, f"unsupported component {part}")
        values.append(float(number.group(1)) / (256.0 if "/" in part else 1.0))
    return tuple(values)


def amiga(rgb):
    # The shader output is clamped to [0,1] and stored as 8-bit, then the
    # Amiga keeps four bits per gun.
    eight = [round(min(1.0, max(0.0, c)) * 255) for c in rgb]
    four = [(v * 15 + 127) // 255 for v in eight]
    return (four[0] << 8) | (four[1] << 4) | four[2], eight


def generate(data_path, assembly_path, output):
    data = data_path.read_bytes()
    assembly = assembly_path.read_text(encoding="utf-8")
    table = shaders(data)
    rows = []
    for shader_id, name in palette_list(assembly):
        shader_name, fragment = table[shader_id]
        main = fragment[fragment.index("void main"):]
        require("whiteOrNot" in main and "redOrNot" in main and "blackOrNot" in main,
                f"{shader_name} is not a four-class palette shader")
        colours = {}
        for key in "LMDS":
            found = re.findall(r"^\s*color" + key + r"\s*=\s*([^;]+);", main, re.M)
            require(found, f"{shader_name} has no color{key}")
            colours[key] = amiga(colour(found[-1]))
        rows.append((shader_id, shader_name, name, colours))
    lines = ["// Generated by generate-palettes.py from data.win; do not commit.",
             "#include \"core/Palettes.h\"",
             "namespace downwell::palettes {",
             "static const PaletteEntry entries[] = {"]
    for shader_id, shader_name, name, colours in rows:
        lines.append("    {\"%s\",%d,0x%03x,0x%03x,0x%03x,0x%03x}, // %s" % (
            name, shader_id, colours["L"][0], colours["M"][0], colours["D"][0], colours["S"][0],
            shader_name))
    lines += ["};", "static constexpr unsigned count=sizeof(entries)/sizeof(entries[0]);", "}"]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    manifest = {"schemaVersion": 1,
                "tool": {"name": Path(__file__).name, "version": VERSION,
                         "sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest()},
                "inputs": [{"name": data_path.name, "sha256": hashlib.sha256(data).hexdigest()},
                           {"name": assembly_path.name,
                            "sha256": hashlib.sha256(assembly.encode("utf-8")).hexdigest()}],
                "paletteCount": len(rows),
                "outputSha256": hashlib.sha256(output.read_bytes()).hexdigest()}
    output.with_suffix(".json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Prepared {len(rows)} palettes")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=ROOT / "data/data.win")
    parser.add_argument("--assembly", type=Path, default=ROOT /
                        "extracted/utmt-0.9.2.0/Assembly/gml_GlobalScript_scrShaderListInit.asm")
    parser.add_argument("--output", type=Path, default=ROOT / "generated/downwell-palettes.h")
    args = parser.parse_args()
    generate(args.data, args.assembly, args.output)
