#!/usr/bin/env python3
"""Offline Paula PCM for the explicitly admitted TimeFieldWind resources."""
import hashlib
import json
from pathlib import Path
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[1]
VERSION = "amiga-wind-bank/v1"
IDS = tuple(range(349, 356))
RATE = 22030
PERIOD = 161  # PAL 3546895 / 161 = 22030.4037 Hz.
BUDGET = 2 * 1024 * 1024  # Fast source storage, never a Chip allocation.
HEADER = struct.Struct(">4sHHIII")
ENTRY = struct.Struct(">III")


def digest(data):
    return hashlib.sha256(data).hexdigest()


def pack(samples):
    if set(samples) != set(IDS):
        raise ValueError("Wind admission requires exactly resources 349–355")
    offset = HEADER.size + ENTRY.size * len(IDS)
    table, payload = bytearray(), bytearray()
    for resource in IDS:
        pcm = samples[resource]
        if not pcm:
            raise ValueError("Empty wind sample")
        table += ENTRY.pack(resource, offset, len(pcm))
        padded = pcm + (b"\0" if len(pcm) & 1 else b"")
        payload += padded
        offset += len(padded)
    if offset > BUDGET:
        raise ValueError("Wind bank exceeds reviewed Fast RAM budget")
    return HEADER.pack(b"DWWA", 1, len(IDS), RATE, PERIOD, offset) + table + payload


def decode(path):
    # No normalisation or gain bake: resource gain and voice gain remain runtime
    # state. Explicit mono admission below avoids an undocumented stereo mix.
    return subprocess.run([
        "ffmpeg", "-nostdin", "-v", "error", "-i", str(path),
        "-map", "0:a:0", "-ac", "1", "-ar", str(RATE),
        "-af", "aresample=dither_method=none", "-c:a", "pcm_s8",
        "-f", "s8", "pipe:1"], check=True, capture_output=True).stdout


def generate(root):
    metadata_path = root / "extracted/audio/manifest.json"
    metadata_bytes = metadata_path.read_bytes()
    metadata = json.loads(metadata_bytes)
    source_hash = digest((root / "data/data.win").read_bytes())
    if source_hash != metadata["sources"]["data/data.win"]["sha256"]:
        raise ValueError("Audio extraction does not match data.win")
    records = [r for r in metadata["sounds"] if r["id"] in IDS]
    if len(records) != len(IDS) or {r["id"] for r in records} != set(IDS):
        raise ValueError("Missing or duplicate wind resource metadata")
    samples, inputs = {}, {}
    for record in sorted(records, key=lambda r: r["id"]):
        if record["volume"] != 1.0 or record["effects"] != 0:
            raise ValueError("Wind gain/effects changed; review audio admission")
        path = (root / "extracted/audio" / record["output"]).resolve()
        if not path.is_relative_to((root / "extracted/audio").resolve()):
            raise ValueError("Audio path leaves extraction directory")
        raw = path.read_bytes()
        if digest(raw) != record["sha256"]:
            raise ValueError("Extracted audio hash mismatch")
        info = json.loads(subprocess.run([
            "ffprobe", "-v", "error", "-select_streams", "a", "-show_streams",
            "-of", "json", str(path)], check=True, capture_output=True).stdout)
        streams = info["streams"]
        if len(streams) != 1 or streams[0]["channels"] != 1:
            raise ValueError("Wind bank admits only original mono samples")
        samples[record["id"]] = decode(path)
        inputs[str(record["id"])] = {
            "path": record["output"], "sha256": digest(raw),
            "sourceRate": streams[0]["sample_rate"],
            "samples": len(samples[record["id"]]), "gain": record["volume"]}
    bank = pack(samples)
    manifest = {
        "schemaVersion": 1, "generator": VERSION,
        "generatorSha256": digest(Path(__file__).read_bytes()),
        "ffmpeg": subprocess.run(["ffmpeg", "-version"], check=True,
                                 capture_output=True, text=True).stdout.splitlines()[0],
        "extractor": metadata["extractor"],
        "resourceMetadata": metadata["resourceMetadata"],
        "audioManifestSha256": digest(metadata_bytes), "dataWinSha256": source_hash,
        "resources": inputs, "sampleRate": RATE, "palPeriod": PERIOD,
        "format": "signed 8-bit mono; no normalisation, gain bake or dither",
        "bytes": len(bank), "budget": BUDGET, "sha256": digest(bank)}
    output = root / "generated"
    output.mkdir(exist_ok=True)
    for name, content in (
        ("amiga-wind.bin", bank),
        ("amiga-wind.json", (json.dumps(manifest, indent=2) + "\n").encode()),
        ("amiga-wind.h", ("// Generated by " + VERSION + "; do not edit.\n"
          "#pragma once\n"
          f"#define DOWNWELL_WIND_BANK_BYTES {len(bank)}u\n"
          f"#define DOWNWELL_WIND_BANK_BUDGET {BUDGET}u\n").encode())):
        destination = output / name
        if not destination.resolve().is_relative_to((root / "generated").absolute()) or destination.is_symlink():
            raise ValueError("Refusing redirected output")
        destination.write_bytes(content)
    print(f"Wind bank: {len(bank)} Fast bytes, {len(samples)} resources; no linked PCM")


if __name__ == "__main__":
    generate(ROOT)
