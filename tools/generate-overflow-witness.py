#!/usr/bin/env python3
"""Export post-Step observations from the source-checked pinned overflow replay."""
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]


def main():
    result = subprocess.run(["build/amiga-currency-promotion-test", "--overflow", "--witness"],
                            cwd=ROOT, text=True, capture_output=True)
    if result.returncode:
        sys.stderr.write(result.stdout + result.stderr)
        result.check_returncode()
    records = []
    configurations = [dict(item.split("=") for item in line.split()[1:])
                      for line in result.stdout.splitlines() if line.startswith("OVERFLOW_CONFIG ")]
    assert len(configurations) == 1
    config = configurations[0]
    for line in result.stdout.splitlines():
        if not line.startswith("WITNESS "):
            continue
        fields = line.split()
        assert int(fields[1]) == len(records) + 1 and len(fields) == 12
        records.append([int(v, 16) for v in fields[2:]])
    assert len(records) == 1800
    output = ROOT / "generated/overflow-witness.h"
    output.write_text("// Generated by generate-overflow-witness.py v2; verification only.\n"
                      "static const unsigned long overflowWitness[1800][10]={\n" +
                      "".join("{" + ",".join(f"0x{v:08x}UL" for v in row) + "},\n"
                              for row in records) + "};\n")
    inputs = [ROOT / name for name in (
        "generated/downwell-rooms.dwrm", "generated/downwell-objects.dwob",
        "generated/downwell-builder-patterns.dwbp", "generated/amiga-game.dwap",
        "tests/platform/amiga/AmigaCurrencyPromotionTest.cpp",
        "tests/platform/amiga/AmigaSceneRuntimeTest.cpp", "build/amiga-currency-promotion-test")]
    inputs += sorted((ROOT / "src/core").glob("*.[ch]*"))
    inputs += sorted((ROOT / "src/platform/amiga").glob("*.[ch]*"))
    sha = lambda path: hashlib.sha256(path.read_bytes()).hexdigest()
    manifest = {"tool": Path(__file__).name, "version": 2, "schema": 1,
                "seed": int(config["seed"]), "route": int(config["route"]), "frames": len(records),
                "tool_sha256": sha(Path(__file__)), "header_sha256": sha(output),
                "inputs": {str(p.relative_to(ROOT)): sha(p) for p in inputs if p.is_file()}}
    output.with_suffix(".manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print("Source-checked overflow witness: 1800 post-Step frames, five observation groups")


if __name__ == "__main__":
    main()
